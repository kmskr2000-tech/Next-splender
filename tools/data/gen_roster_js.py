#!/usr/bin/env python3
"""Generate src/data/roster.js and sync names in src/data/cards.js from docs/design/roster-korea.json.
Usage: python3 tools/data/gen_roster_js.py   (run from repo root or anywhere)
Only `name` fields in cards.js are touched; numeric fields are never modified."""
import json, re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
d = json.loads((root/'docs/design/roster-korea.json').read_text(encoding='utf-8'))
q = lambda s: json.dumps(s, ensure_ascii=False)
out = ["// 한국 로스터 표시 데이터 (docs/design/roster-korea.json 발췌): id -> { line_id, relation, desc }.",
       "// 규칙 수치는 cards.js 가 단일 출처. GENERATED by tools/data/gen_roster_js.py — 직접 수정 금지.", "",
       "export const LINES = {"]
for l in d['lines']:
    out.append(f"  {l['line_id'] if re.fullmatch(r'[A-Za-z_]\w*', l['line_id']) else q(l['line_id'])}: {{ title: {q(l['title'])}, summary: {q(l['summary'])} }},")
out += ["};", "", "export const ROSTER = {"]
for c in d['cards']:
    out.append(f"  {q(c['id']).replace(chr(34),chr(39))}: {{ line_id: {q(c['line_id'])}, relation: {q(c['relation'])}, desc: {q(c['desc'])} }},")
out += ["};", ""]
(root/'src/data/roster.js').write_text("\n".join(out), encoding='utf-8')
p = root/'src/data/cards.js'; s = p.read_text(encoding='utf-8'); n = 0
for c in d['cards']:
    s, k = re.subn(r"(\{ id: '%s',[^\n]*? name: )'[^']*'" % c['id'], lambda m: m.group(1)+"'"+c['name'].replace("'", "\\'")+"'", s)
    assert k == 1, c['id']; n += 1
p.write_text(s, encoding='utf-8'); print('cards synced', n)
